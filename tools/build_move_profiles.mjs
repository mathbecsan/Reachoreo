// Measures every 4-count piece of Encendido's 19 phrases (both robots and the dancer, from the stage module):
// where its hits land (per half-count), how much it moves, and the pose it starts and ends in. The song-dance
// generator (choreography/library.py) uses this to put hits on the music's accents and to join pieces smoothly.
//
//   node tools/build_move_profiles.mjs        # -> reachy_dance/choreography/move_profiles.json
// tests/test_library.py checks the file is up to date with the stage module.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const C = await import(path.join(ROOT, "reachy_dance/dashboard/static/encendido-stage.mjs"));
const deg = 180 / Math.PI;
export const ROBOT_KEYS = ["yaw", "pitch", "roll", "body", "antL", "antR", "bob"];
export const HUMAN_KEYS = ["aL", "eL", "aR", "eR", "look", "x", "drop", "face", "shrug", "lean"];
// one unit ~ one degree of visible motion
const robotVec = r => [r.yaw * 40, r.pitch * 25, r.roll * deg, r.body * 30 + r.turn * deg, r.antL * 30, r.antR * 30, r.bob];
const humanVec = h => [h.aL * 40, h.eL * 30, h.aR * 40, h.eR * 30, h.look * 20, h.x / 5, h.drop * 0.6, h.face * deg / 3, h.shrug * 0.6, h.lean * deg];
const STEPS = 20;                                   // samples per count

export function profile(src, half) {
  const at = c => { const S = C.raw(src, src * C.PH + (4 * half + Math.min(3.999, Math.max(0, c))) * C.BEAT); return { A: robotVec(S.L), B: robotVec(S.R), H: humanVec(S.H) }; };
  const n = 4 * STEPS, speed = { R: [], H: [] };
  let prev = at(0);
  for (let i = 1; i <= n; i++) {
    const cur = i === n ? at(0) : at(i / STEPS), d = (a, b) => a.reduce((s, x, k) => s + Math.abs(x - b[k]), 0) * STEPS;
    speed.R.push((d(cur.A, prev.A) + d(cur.B, prev.B)) / 2); speed.H.push(d(cur.H, prev.H)); prev = cur;
  }
  // a hit: motion that starts (or jumps) right on the half-count
  const accents = key => {
    const s = speed[key], out = [];
    for (let q = 0; q < 8; q++) {
      // the 4 counts are read as a loop, so count 1's "before" is the end of the piece (moves repeat in 4s)
      const i0 = q * STEPS / 2, w = i => s[(i + s.length) % s.length];
      // w(i) is the motion from sample i to i+1, so w(i0 - 1) is the snap arriving exactly on the half-count
      // On count 1 the arriving step is the loop seam (end back to start). Part of it is a real snap (beats restart),
      // part is just the piece not ending where it began, which a real dance crossfades: cap it at the size of the
      // snaps that arrive on the piece's other counts.
      const onCount = [2, 4, 6].map(k => s[k * STEPS / 2 - 1]).sort((a, b) => a - b)[1];
      const after = Array.from({ length: Math.round(0.3 * STEPS) }, (_, k) => q || k ? w(i0 - 1 + k) : Math.min(w(-1), 1.5 * onCount));
      const before = Array.from({ length: Math.round(0.25 * STEPS) }, (_, k) => w(i0 - 2 - k));
      const mb = before.reduce((a, b) => a + b, 0) / before.length;
      out.push(Math.max(0, Math.max(...after) - mb));
    }
    const tot = out.reduce((a, b) => a + b, 0);
    return tot > 1e-6 ? out.map(v => v / tot) : out.map(() => 0);
  };
  const aR = accents("R"), aH = accents("H"), mean = v => v.reduce((a, b) => a + b, 0) / v.length;
  const r4 = v => v.map(x => +x.toFixed(4));
  return {
    src, half, accents: r4(aR.map((v, q) => 0.5 * v + 0.5 * aH[q])), robot_accents: r4(aR), human_accents: r4(aH),
    energy: +(0.5 * mean(speed.R) + 0.5 * mean(speed.H)).toFixed(2),
    start: { A: r4(at(0.02).A), B: r4(at(0.02).B), H: r4(at(0.02).H) },
    end: { A: r4(at(3.98).A), B: r4(at(3.98).B), H: r4(at(3.98).H) },
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const pieces = [];
  for (let src = 0; src < C.N; src++) for (const half of [0, 1]) pieces.push(profile(src, half));
  const out = { note: "GENERATED by tools/build_move_profiles.mjs; do not edit", robot_keys: ROBOT_KEYS, human_keys: HUMAN_KEYS, pieces };
  const file = path.join(ROOT, "reachy_dance/choreography/move_profiles.json");
  const text = JSON.stringify(out, null, 0).replace(/\{"src"/g, '\n{"src"') + "\n";
  if (process.argv.includes("--check")) { process.stdout.write(fs.readFileSync(file, "utf8") === text ? "same" : "different"); }
  else { fs.writeFileSync(file, text); console.log(`wrote ${path.relative(ROOT, file)} (${pieces.length} pieces)`); }
}
