"""Builds the dashboard's choreography module from the animated preview, so the rehearsal page shows
exactly the preview's motion and drawings (no hand-copied second version to drift out of date).

    python tools/build_stage_js.py      # preview/encendido-preview.html -> reachy_dance/dashboard/static/encendido-stage.mjs

Run it again after editing the preview. tests/test_stage_js.py checks the result still matches the golden robot motion.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "preview" / "encendido-preview.html"
OUT = ROOT / "reachy_dance" / "dashboard" / "static" / "encendido-stage.mjs"


def between(text: str, start: str, end: str) -> str:
    a = text.index(start)
    b = text.index(end, a)
    return text[a:b]


def main():
    html = SRC.read_text()
    motion = between(html, "const BPM = 120", "// ---------- drawing ----------")
    consts = between(html, "const VW = 1600", "\n") + "\n"
    drawing = between(html, "function rr(x, y, w, h, r)", "function drawHud(t)")
    OUT.write_text(f"""// GENERATED by tools/build_stage_js.py from preview/encendido-preview.html. Do not edit by hand.
// The preview's choreography (both robots and the dancer, every count) and its stage drawings.
let ctx = null;
export function setContext(c) {{ ctx = c; }}

{motion}
{consts}
{drawing}
export {{ BPM, BEAT, PH, N, DUR, ACTS, PHRASES, POS, VW, VH, FLOOR, TOP, poseAt, raw, phraseAt,
         drawKitchen, drawRobot, drawHuman, robot, human }};
""")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
